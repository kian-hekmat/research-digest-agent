MODEL = "fake-embed"


def _vec(angle):
    v = [0.0] * EMBEDDING_DIM
    v[0], v[1] = math.cos(math.radians(angle)), math.sin(math.radians(angle))
    return v


class KeywordEmbedder:
    """Puts 'results'/'speedup' text near the results query and everything
    else near the method query, so retrieval is predictable."""

    enabled = True
    model = MODEL

    def embed(self, texts):
        out = []
        for t in texts:
            low = t.lower()
            if "quantitative results" in low or "speedup" in low:
                out.append(_vec(0))
            elif "limitations" in low or "fails" in low:
                out.append(_vec(90))
            else:
                out.append(_vec(45))
        return out


