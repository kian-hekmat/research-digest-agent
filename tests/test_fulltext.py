def test_throttle_spaces_requests_across_threads(monkeypatch):
    """arXiv allows one request per 3s over one connection; concurrent
    digests share the worker process, so the gate must hold across threads."""
    monkeypatch.setattr(arxiv_module, "_last_request_at", 0.0)
    stamps = []

    def call():
        arxiv_module.throttle(0.2)
        stamps.append(time.monotonic())

    threads = [threading.Thread(target=call) for _ in range(3)]
    for t in threads:
        t.start()
    for t in threads:
        t.join()
    stamps.sort()
    assert all(b - a >= 0.19 for a, b in zip(stamps, stamps[1:]))


