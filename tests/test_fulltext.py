@respx.mock
def test_excerpts_go_after_the_abstract_and_the_rating_is_a_separate_call():
    route = respx.post("http://ollama.test:11434/api/chat").mock(
        side_effect=[
            httpx.Response(200, json={"message": {"content": "Relevance: 9\n\nS."}}),
            httpx.Response(200, json={"message": {"content": "4"}}),
        ]
    )
    s = Summarizer(Settings(summary_backend="ollama", ollama_base_url="http://ollama.test:11434"))

    out = s.summarize_and_rate("T", "A.", "PINNs", "pinns", excerpts=["[2 Results] 12x faster."])

    assert (out.summary, out.relevance) == ("S.", 4)  # the abstract-only rating wins
    summary_call, rating_call = (json.loads(c.request.content)["messages"] for c in route.calls)
    assert summary_call[0]["content"] == summarize_module._RATED_SUMMARY_SYSTEM + summarize_module._FULLTEXT_NOTE
    assert summary_call[1]["content"].endswith("Abstract: A.\n\nExcerpts from the full text:\n[2 Results] 12x faster.")
    assert rating_call[0]["content"] == summarize_module._RELEVANCE_SYSTEM
    assert "Excerpts" not in rating_call[1]["content"]


