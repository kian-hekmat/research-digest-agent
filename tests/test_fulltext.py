# ---------- parsing ----------
def test_parse_keeps_body_and_captions_and_skips_front_matter_notes_tables_refs():
    sections = parse_sections(HTML)

    assert [s.title for s in sections] == ["1 Introduction", "2 Results"]
    assert sections[0].paragraphs == ("We solve $u_t=\\Delta u$ fast.",)
    assert sections[1].paragraphs == ("The error drops to 1e-6 with a 12x speedup.", "Caption: Figure 1: Convergence.")
    flat = json.dumps([s.paragraphs for s in sections])
    for absent in ("abstract", "footnote", "0.123", "Someone", "ada@example.org"):
        assert absent not in flat


def test_long_formulas_are_elided():
    html = '<section><h2 class="ltx_title ltx_title_section">1 A</h2><p class="ltx_p">x <math alttext="' + "a+" * 50 + 'b"></math> y</p></section>'
    assert parse_sections(html)[0].paragraphs == ("x [formula] y",)


# ---------- chunking ----------
def test_chunks_pack_paragraphs_without_crossing_sections():
    sections = [Section("1 A", ("a" * 500, "b" * 500, "c" * 500)), Section("2 B", ("d" * 100,))]

    chunks = chunk_sections(sections, max_chars=1100)

    assert [(c.section, len(c.text)) for c in chunks] == [("1 A", 1001), ("1 A", 500), ("2 B", 100)]


def test_overlong_paragraph_splits_at_sentences_and_chunks_are_capped():
    para = " ".join(f"Sentence {i} is here." for i in range(200))
    chunks = chunk_sections([Section("1 A", (para,))], max_chars=300, max_chunks=5)
    assert len(chunks) == 5
    assert all(len(c.text) <= 300 and c.text.endswith(".") for c in chunks)


