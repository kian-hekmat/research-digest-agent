    assert temporal_activities.fetch_fulltext(FetchFulltextInput(paper_ids=[paper.id])) == 1
    assert temporal_activities.fetch_fulltext(FetchFulltextInput(paper_ids=[paper.id])) == 0
    assert calls == ["2610.00001"]


