    monkeypatch.setattr(settings, "summary_backend", "ollama")
    monkeypatch.setattr(temporal_activities, "Embedder", KeywordEmbedder)
    monkeypatch.setattr(temporal_activities.activity, "heartbeat", lambda *a: None)
    calls = []

    def fake_index(db, embedder, p, fetch=None):
        calls.append(p.arxiv_id)
        p.fulltext_status = "ok"
        db.commit()
        return "ok"

