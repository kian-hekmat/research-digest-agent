def test_excerpts_are_the_best_chunk_per_query_in_paper_order(db_session, paper):
    chunks = [Chunk("1 Intro", "Background text."), Chunk("2 Method", "We propose a scheme."),
              Chunk("3 Results", "A 12x speedup over FEM."), Chunk("4 Discussion", "It fails for stiff cases.")]
    retrieval.store_chunks(db_session, KeywordEmbedder(), paper, chunks)
    db_session.commit()

    got = retrieval.fulltext_excerpts(db_session, KeywordEmbedder(), paper.id, max_excerpts=4)

    assert "[3 Results] A 12x speedup over FEM." in got
    assert "[4 Discussion] It fails for stiff cases." in got
    assert got == sorted(got, key=lambda c: [ch.section for ch in chunks].index(c[1:].split("]")[0]))


